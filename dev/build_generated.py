"""Genera módulos JS a partir de fuentes: datos semilla (desde seed_data.py), dimensiones de imágenes semilla y fragmentos HTML."""
import importlib.util, json, os, re, sys
from pathlib import Path
from PIL import Image
W = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("sd", "/home/claude/thf/app/thf/seed_data.py")
sd = importlib.util.module_from_spec(spec); spec.loader.exec_module(sd)
dims = {}
for f in sorted((W / "public/media/seed").iterdir()):
    if f.suffix == ".webp" and not f.name.startswith("al-"):  # al-*: fotos de demostración para aliadas (solo dev/demo.mjs)
        with Image.open(f) as im:
            dims[f.stem] = [im.width, im.height, f.stat().st_size]
    elif f.suffix == ".mp4":
        dims[f.name] = [0, 0, f.stat().st_size]
data = {k: getattr(sd, k) for k in ["SETTINGS", "CATEGORIES", "COLLECTIONS", "PLACES", "LEAD", "ALISIOS", "FEATURED", "VENEZUELA", "CANDY", "RELIGIOSA", "LOOKS", "SHIPPING", "PAYMENTS", "DIGITAL", "PAGES", "PAGE_CONTENT", "STATES", "MAP_POS", "PLACE_FIX", "NOTIFY_TEMPLATES", "CAMPAIGNS", "SUPPLIERS", "MATERIALS", "BOM"]}
data["MEDIA"] = dims
(W / "src/lib/seed-data.js").write_text("// Generado por dev/build_generated.py — no editar a mano\nexport const SEED = " + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
# fragmentos HTML de páginas largas
frag = {}
for f in sorted((W / "src/fragments").glob("*.html")):
    frag[f.stem] = f.read_text(encoding="utf-8")
(W / "src/views/fragments.js").write_text("// Generado por dev/build_generated.py desde src/fragments/*.html — no editar a mano\nexport const FRAG = " + json.dumps(frag, ensure_ascii=False) + ";\n", encoding="utf-8")
print("seed media:", len(dims), "fragments:", list(frag))
# esquema SQL como lista de sentencias (D1 ejecuta en lote, sin BEGIN/COMMIT) + migraciones + versión PostgreSQL (Supabase)
def split_sql(text):
    text = "\n".join(re.sub(r"--.*$", "", l) for l in text.splitlines())
    out, buf = [], ""
    for part in re.split(r"(;)", text):
        buf += part
        if part == ";":
            st = buf.strip()
            # los triggers llevan ";" dentro de BEGIN ... END
            if re.match(r"(?is)^CREATE\s+TRIGGER", st) and not re.search(r"(?is)\bEND\s*;$", st):
                continue
            st = re.sub(r"\s+", " ", st.rstrip(";")).strip()
            if st and not st.upper().startswith("PRAGMA"):
                out.append(st)
            buf = ""
    if buf.strip():
        out.append(re.sub(r"\s+", " ", buf).strip())
    return out

TRIG = re.compile(r"(?i)^CREATE TRIGGER (\w+) BEFORE (UPDATE|DELETE) ON (\w+) BEGIN SELECT RAISE\(ABORT, '([^']*)'\); END$")
def to_pg(st):
    m = TRIG.match(st)
    if m:
        name, op, tbl, msg = m.groups()
        return f"CREATE TRIGGER {name} BEFORE {op.upper()} ON {tbl} FOR EACH ROW EXECUTE FUNCTION thf_immutable()"
    st = re.sub(r"\bINTEGER PRIMARY KEY\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", st)
    st = re.sub(r"\bINTEGER\b", "BIGINT", st)
    st = re.sub(r"\bREAL\b", "DOUBLE PRECISION", st)
    st = re.sub(r"\bBLOB\b", "BYTEA", st)
    st = st.replace(" COLLATE NOCASE", "")
    return st

schema = split_sql((W / "schema.sql").read_text(encoding="utf-8"))
migs = []
for f in sorted((W / "migrations").glob("*.sql")):
    v = int(f.name.split("_")[0])
    migs.append({"version": v, "name": f.stem, "sql": split_sql(f.read_text(encoding="utf-8"))})
PG_PRE = ["CREATE OR REPLACE FUNCTION thf_immutable() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'registro inmutable: %', TG_TABLE_NAME; END $$"]
schema_pg = PG_PRE + [to_pg(s) for s in schema]
migs_pg = [{**m, "sql": [to_pg(s) for s in m["sql"]]} for m in migs]
(W / "src/lib/schema.js").write_text("// Generado por dev/build_generated.py desde schema.sql y migrations/*.sql — no editar a mano\n"
    + "export const SCHEMA = " + json.dumps(schema, ensure_ascii=False, indent=0) + ";\n"
    + "export const MIGRATIONS = " + json.dumps(migs, ensure_ascii=False, indent=0) + ";\n"
    + "export const SCHEMA_PG = " + json.dumps(schema_pg, ensure_ascii=False, indent=0) + ";\n"
    + "export const MIGRATIONS_PG = " + json.dumps(migs_pg, ensure_ascii=False, indent=0) + ";\n"
    + f"export const LATEST = {max([1] + [m['version'] for m in migs])};\n", encoding="utf-8")
# Archivo SQL para pegar en Supabase (SQL Editor) si se prefiere crear la base a mano
tables = sorted(set(re.findall(r"(?i)CREATE TABLE (?:IF NOT EXISTS )?(\w+)", "\n".join(schema + [s for m in migs for s in m["sql"]]))))
rls = [f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY" for t in tables]
lock = ["DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated; REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated; REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM anon, authenticated; END IF; END $$"]
(W / "supabase").mkdir(exist_ok=True)
(W / "supabase/schema.sql").write_text("-- Generado por dev/build_generated.py — esquema completo de THF para Supabase (PostgreSQL).\n-- No hace falta pegarlo: /setup lo crea solo. Sirve para revisar o crear la base a mano.\n\n"
    + ";\n".join(schema_pg + [s for m in migs_pg for s in m["sql"]] + [f"INSERT INTO schema_version(version, applied_at) VALUES ({v}, to_char(now() at time zone 'utc','YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"'))" for v in [1] + [m['version'] for m in migs]] + rls + lock) + ";\n", encoding="utf-8")
print("schema statements:", len(schema), "migrations:", [(m["version"], len(m["sql"])) for m in migs], "tables:", len(tables))
